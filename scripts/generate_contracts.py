"""Generate JSON Schema and TypeScript from C02's Pydantic contracts.

No network or third-party code generator is required. Unsupported schema
constructs fail explicitly instead of silently becoming `any`.
"""
import argparse
import importlib
import inspect
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'packages/core/src'))

from pydantic import BaseModel, TypeAdapter
from opendirector.domain.creation.schema import ALIASES, CreationContracts
from opendirector.domain.rule_facts import typescript_module

MODULES = ('base', 'assets', 'models', 'generation', 'editors', 'canvas', 'project', 'commands', 'schema')


def models():
    result = {}
    for module in MODULES:
        namespace = importlib.import_module('opendirector.domain.creation.' + module)
        for value in vars(namespace).values():
            if inspect.isclass(value) and issubclass(value, BaseModel) and value.__module__.startswith('opendirector.domain.creation'):
                result[value.__name__] = value
    return result


def schema_catalog(mode, definitions):
    root = CreationContracts.model_json_schema(mode=mode)
    for name, model in sorted(definitions.items()):
        schema = model.model_json_schema(mode=mode)
        nested = schema.pop('$defs', {})
        for key, value in nested.items():
            if key in root['$defs'] and root['$defs'][key] != value:
                raise ValueError(f'Conflicting schema {key}')
            root['$defs'][key] = value
        root['$defs'][name] = schema
    root['$defs'] = dict(sorted(root['$defs'].items()))
    return root


def ts_type(schema, suffix):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[-1] + suffix
    if 'const' in schema:
        return json.dumps(schema['const'], ensure_ascii=False)
    if 'enum' in schema:
        return ' | '.join(json.dumps(value, ensure_ascii=False) for value in schema['enum'])
    for keyword in ('oneOf', 'anyOf'):
        if keyword in schema:
            return ' | '.join(dict.fromkeys(ts_type(value, suffix) for value in schema[keyword]))
    if 'allOf' in schema:
        return ' & '.join('(' + ts_type(value, suffix) + ')' for value in schema['allOf'])
    kind = schema.get('type')
    if kind in {'string', 'boolean', 'null'}:
        return kind
    if kind in {'number', 'integer'}:
        return 'number'
    if kind == 'array':
        if 'prefixItems' in schema:
            return 'readonly [' + ', '.join(ts_type(value, suffix) for value in schema['prefixItems']) + ']'
        return 'ReadonlyArray<' + ts_type(schema.get('items', {}), suffix) + '>'
    if kind == 'object':
        props = schema.get('properties', {})
        if props:
            required = set(schema.get('required', []))
            fields = [f'readonly {json.dumps(key)}{"" if key in required else "?"}: {ts_type(value, suffix)}'
                      for key, value in props.items()]
            return '{ ' + '; '.join(fields) + ' }'
        additional = schema.get('additionalProperties', False)
        if isinstance(additional, dict):
            return 'Readonly<Record<string, ' + ts_type(additional, suffix) + '>>'
        if additional is True:
            return 'Readonly<Record<string, unknown>>'
        return 'Readonly<Record<string, never>>'
    if not schema:
        return 'unknown'
    raise ValueError(f'Unsupported schema construct: {schema}')


def typescript(catalogs, definitions):
    lines = ['// Generated by scripts/generate_contracts.py. Do not edit.',
             '// Names without Input describe normalized JSON output; Input permits declared defaults.',
             '// Runtime constraints and cross-object validation are enforced by the Python contracts.', '']
    for mode, suffix in [('input', 'Input'), ('output', '')]:
        catalog = catalogs[mode]
        for name, schema in catalog['$defs'].items():
            if schema.get('type') != 'object' or 'properties' not in schema:
                lines += [f'export type {name}{suffix} = {ts_type(schema, suffix)};', '']
                continue
            parent = None
            model = definitions.get(name)
            if model:
                parent = next((base.__name__ for base in model.__bases__ if base.__name__ != name and base.__name__ in definitions), None)
            base = catalog['$defs'].get(parent, {}) if parent else {}
            base_properties = base.get('properties', {})
            required = set(schema.get('required', []))
            base_required = set(base.get('required', []))
            extends = f' extends {parent}{suffix}' if parent else ''
            lines.append(f'export interface {name}{suffix}{extends} {{')
            for key, prop in schema['properties'].items():
                if key in base_properties and prop == base_properties[key] and (key in required) == (key in base_required):
                    continue
                lines.append(f'  readonly {key}{"" if key in required else "?"}: {ts_type(prop, suffix)};')
            lines += ['}', '']
        for name, alias in ALIASES.items():
            schema = TypeAdapter(alias).json_schema(mode='validation' if mode == 'input' else 'serialization')
            lines += [f'export type {name}{suffix} = {ts_type(schema, suffix)};', '']
    return '\n'.join(lines)


def artifacts():
    definitions = models()
    catalogs = {'input': schema_catalog('validation', definitions), 'output': schema_catalog('serialization', definitions)}
    document = {'contractVersion': 1, 'projectFormat': 'opendirector-project', 'projectFormatVersion': 2, **catalogs}
    return {
        ROOT / 'src/contracts/creation.schema.json': json.dumps(document, ensure_ascii=False, indent=2) + '\n',
        ROOT / 'src/contracts/generated.ts': typescript(catalogs, definitions),
        ROOT / 'src/contracts/ruleFacts.generated.ts': typescript_module(),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, contents in artifacts().items():
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != contents:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            # Generated contracts contain non-ASCII text; the locale default (GBK on
            # Chinese Windows) cannot round-trip them.
            path.write_text(contents, encoding='utf-8')
    if stale:
        parser.error('Out-of-date generated contracts: ' + ', '.join(stale))
    print('Creation contracts ' + ('verified' if args.check else 'generated'))


if __name__ == '__main__':
    main()
